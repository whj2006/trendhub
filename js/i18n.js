let currentLang = localStorage.getItem("trendhub_lang") || "es";

function t(key, vars) {
  const dict = I18N[currentLang] || I18N.es;
  let str = dict[key] !== undefined ? dict[key] : (I18N.es[key] || key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(`{${k}}`, v);
    }
  }
  return str;
}

function applyTranslations() {
  document.documentElement.lang = currentLang;

  // 文本内容
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    el.textContent = t(key);
  });

  // placeholder
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    el.placeholder = t(key);
  });

  // value (按钮等)
  document.querySelectorAll("[data-i18n-value]").forEach(el => {
    const key = el.getAttribute("data-i18n-value");
    el.value = t(key);
  });

  // title 标签
  const titleKey = document.querySelector("[data-i18n-title]");
  if (titleKey) {
    document.title = t(titleKey.getAttribute("data-i18n-title"));
  }

  // 语言切换按钮文字
  const langBtn = document.getElementById("langToggle");
  if (langBtn) {
    langBtn.textContent = currentLang === "es" ? "EN" : "ES";
  }
}

function toggleLang() {
  currentLang = currentLang === "es" ? "en" : "es";
  localStorage.setItem("trendhub_lang", currentLang);
  applyTranslations();

  // 重新渲染动态内容（如果有当前页的渲染函数）
  if (typeof pintarPrincipal === "function") pintarPrincipal();
  if (typeof aplicar === "function") aplicar();
  if (typeof aplicarFiltros === "function") aplicarFiltros();
  if (typeof pintarDetalle === "function") pintarDetalle();
  if (typeof gestionarResultados === "function") gestionarResultados();
}

// 初始化
document.addEventListener("DOMContentLoaded", () => {
  applyTranslations();
});
